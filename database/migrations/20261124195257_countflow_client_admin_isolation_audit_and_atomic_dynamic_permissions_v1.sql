CREATE TABLE IF NOT EXISTS public.count_client_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id uuid NOT NULL REFERENCES public.count_clients(id) ON DELETE RESTRICT,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id uuid,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT count_client_audit_log_action_check CHECK (length(btrim(action)) BETWEEN 2 AND 120),
  CONSTRAINT count_client_audit_log_entity_check CHECK (length(btrim(entity_type)) BETWEEN 2 AND 80)
);
